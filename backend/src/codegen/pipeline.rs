//! Driving the whole engine end to end: a decoded IR model in, the SDK source
//! files for the requested targets out, all in memory.
//!
//! [`generate`] is the payload behind the `tono gen` CLI. It produces *rough*
//! source — syntactically valid but unformatted — so it stays pure and
//! deterministic (no language formatter need be installed to test it). Running
//! each language's real formatter and writing to disk is the CLI's job.

use crate::codegen::assemble::{emit_module_files, shared_files};
use crate::codegen::casing::CasingConfig;
use crate::codegen::layout::{go_selector, output_path, SameUnit};
use crate::codegen::modules::{self, CodegenConfig};
pub use crate::codegen::output::{GeneratedFile, TargetKind};
use crate::codegen::render::render_file_with;
use crate::codegen::targets::{go, rust, typescript};
use crate::codegen::tree::ModuleFile;
use crate::codegen::visibility::{self, Exposed};
use crate::codegen::{assemble, reexport, Formatter};
use crate::ir::Model;

/// The banner every generated file carries. The exact `Code generated … DO NOT
/// EDIT.` wording is the convention Go tooling recognizes, and reads the same in
/// Rust and TypeScript.
pub(crate) const BANNER: &str = "// Code generated by tono. DO NOT EDIT.\n\n";

/// The banner's identifying sentence, without comment syntax or spacing, so a
/// check survives whatever the target's formatter does to the line around it.
const BANNER_MARKER: &str = "Code generated by tono. DO NOT EDIT.";

/// Whether `text` is source this generator produced. Lets a caller sweeping an
/// output directory tell its own past output apart from a file someone wrote by
/// hand, which is the difference between clearing a stale artifact and deleting
/// someone's work. Only the opening of the file is considered, so the sentence
/// appearing in a doc comment further down does not make a file look generated.
///
/// One generated file is deliberately not identifiable this way: the TypeScript
/// `package.json`, since JSON carries no comment. It is rewritten on every run,
/// so it is never stale, and staying unidentifiable keeps a hand-edited manifest
/// safe from a sweep.
pub fn is_generated(text: &str) -> bool {
    text.lines()
        .take(3)
        .any(|line| line.contains(BANNER_MARKER))
}

/// The idiomatic casing a target starts from, before any manifest override. A
/// config-driven caller layers `[target.<lang>.casing]` overrides on top with
/// [`CasingConfig::with`]; [`generate`] uses this base for every target.
pub fn casing_for(target: TargetKind) -> CasingConfig {
    match target {
        TargetKind::Rust => rust::types::rust_casing(),
        TargetKind::Go => go::types::go_casing(),
        TargetKind::TypeScript => typescript::types::ts_casing(),
    }
}

/// Render one of a module's output files into rough source text: the banner, then
/// the rendered declarations (with the package clause prepended for Go). The `cat`
/// passthrough keeps the engine's layout without depending on a real formatter.
fn render_module(
    module_file: &ModuleFile,
    target: TargetKind,
    config: &CodegenConfig,
    shares_a_public_unit: bool,
) -> String {
    let passthrough = Formatter::new("cat", vec![]);
    let resolver = SameUnit { target };
    let file = &module_file.file;
    let rendered = match target {
        TargetKind::Rust => {
            // Only a group sharing a file with a public one has to restate its
            // visibility; one that got a fenced file of its own is already out of
            // reach, and saying it twice reads worse.
            let rules = rust::RustRules {
                crate_visible: shares_a_public_unit,
            };
            render_file_with(file, &resolver, &rules, &passthrough).text
        }
        TargetKind::Go => {
            let go_rules = go::GoRules {
                go_module: config.go_module.clone(),
                current: module_file.group.path(),
            };
            let rough = render_file_with(file, &resolver, &go_rules, &passthrough).text;
            // A module's groups are files of one package, named for the module's
            // last segment; the SDK-root group has its own package name.
            let package = go_selector(&module_file.group.path()).unwrap_or_default();
            // The live test file opts out of a default `go test` run: build
            // constraints go before the package clause, so the tag is spliced
            // here rather than emitted as a declaration.
            let tag = match module_file.group.tests_of() {
                Some((_, true)) => "//go:build live\n\n",
                _ => "",
            };
            format!("{tag}{}{}", go::emit::package_clause(&package), rough)
        }
        TargetKind::TypeScript => {
            render_file_with(file, &resolver, &typescript::TsRules, &passthrough).text
        }
    };
    format!("{BANNER}{rendered}")
}

/// Parse a comma-separated target list (e.g. `"rust,go,ts"`) into kinds,
/// rejecting any unknown name.
pub fn parse_targets(csv: &str) -> Result<Vec<TargetKind>, String> {
    csv.split(',')
        .map(|name| {
            let name = name.trim();
            TargetKind::parse(name).ok_or_else(|| format!("unknown target: {name}"))
        })
        .collect()
}

/// The model and the cross-module indices every generation pass needs: the
/// module remap/flatten hooks applied once up front (so render rules and output
/// paths see only effective names), every union's id (so Go can give a struct
/// field a container `UnmarshalJSON` even when its union type is in another
/// module), and the derived set of shapes the SDK exposes.
fn prepare(
    model: &Model,
    config: &CodegenConfig,
) -> (Model, std::collections::HashSet<String>, Exposed) {
    let model = modules::apply(config, model);
    let union_ids: std::collections::HashSet<String> = model
        .modules
        .iter()
        .flat_map(|m| &m.shapes)
        .filter(|s| matches!(s.kind, crate::ir::ShapeKind::Union { .. }))
        .map(|s| s.id.clone())
        .collect();
    let exposed = visibility::derive(&model);
    (model, union_ids, exposed)
}

/// Emit one target's files over an already-prepared model, with the given casing:
/// every group's source file, then the per-module re-exports that make the public
/// groups reachable.
fn emit_target(
    model: &Model,
    target: TargetKind,
    casing: &CasingConfig,
    config: &CodegenConfig,
    union_ids: &std::collections::HashSet<String>,
    exposed: &Exposed,
) -> Vec<GeneratedFile> {
    let mut module_files: Vec<ModuleFile> =
        shared_files(model, target, casing).into_iter().collect();
    module_files.extend(assemble::support_file(model, target));
    for module in &model.modules {
        module_files.extend(emit_module_files(
            module, target, casing, union_ids, exposed,
        ));
    }
    // One pass over the emitted groups records where each symbol ended up; the
    // references are then re-pointed at it, which is what keeps import
    // collection automatic now that a module spans several files.
    assemble::resolve_groups(&mut module_files, target);
    // Which files a public group claims, so an internal group that lands in one
    // of them knows it has to restate its visibility per declaration.
    let public_units: std::collections::HashSet<std::path::PathBuf> = module_files
        .iter()
        .filter(|f| !f.group.is_internal())
        .map(|f| output_path(target, &f.group))
        .collect();
    // The group plus what it exports: the TypeScript barrel names a module's
    // surface one export at a time, and the group has to be read for that before
    // it is folded into whatever file it shares.
    let mut groups: Vec<(crate::codegen::group::Group, typescript::emit::Exports)> =
        Vec::with_capacity(module_files.len());
    let mut files: Vec<GeneratedFile> = Vec::with_capacity(module_files.len());
    for module_file in module_files {
        let path = output_path(target, &module_file.group);
        let shared = module_file.group.is_internal() && public_units.contains(&path);
        let text = render_module(&module_file, target, config, shared);
        // A target may express several of a module's groups in one unit: Rust
        // fences with visibility, so a module's internal group rides its public
        // file rather than moving to one named for its audience. The groups keep
        // their identity (they are still what the symbol index and the re-export
        // tree read); only the file they land in is shared, in emission order.
        match files.iter_mut().find(|f| f.path == path) {
            Some(existing) => existing.text.push_str(text.trim_start_matches(BANNER)),
            None => files.push(GeneratedFile { target, path, text }),
        }
        let exports = match target {
            TargetKind::TypeScript => typescript::emit::exports_of(&module_file.file.decls),
            _ => typescript::emit::Exports::default(),
        };
        groups.push((module_file.group, exports));
    }
    files.extend(match target {
        // Rust needs a module tree so the crate paths resolve, and the `pub use`
        // in it is the module's re-export. Go needs neither: a module is one
        // package already.
        TargetKind::Rust => {
            let groups: Vec<crate::codegen::group::Group> =
                groups.iter().map(|(g, _)| g.clone()).collect();
            reexport::rust_module_tree(&groups)
        }
        TargetKind::TypeScript => reexport::typescript_barrels(&groups),
        TargetKind::Go => Vec::new(),
    });
    files
}

/// Reject a file that still carries a symbol slot.
///
/// A slot is filled when the file is rendered, from the item's own references.
/// One that survives means the emitter wrote the slot but not the reference, so
/// the name would come out with no import behind it: a compile error in the
/// generated SDK, and a confusing one. Catching it here names the file instead.
fn reject_unfilled_slots(files: &[GeneratedFile]) -> Result<(), String> {
    match files.iter().find(|f| f.text.contains('\u{1}')) {
        Some(file) => Err(format!(
            "codegen defect: {} names a symbol with no reference behind it",
            file.path.display()
        )),
        None => Ok(()),
    }
}

/// Reject two files claiming the same path.
///
/// The writer takes the file set in order, so a duplicate would not fail: the
/// second write would replace the first and the SDK would come out silently
/// short. Every path is a function of a group, so a duplicate means two groups
/// map to one place, which is a layout defect and not something a caller can
/// fix by editing the spec. Failing here names both groups instead.
fn reject_duplicate_paths(files: &[GeneratedFile]) -> Result<(), String> {
    let mut seen: std::collections::HashSet<&std::path::Path> = std::collections::HashSet::new();
    for file in files {
        if !seen.insert(&file.path) {
            return Err(format!(
                "codegen defect: two emission groups both map to {}",
                file.path.display()
            ));
        }
    }
    Ok(())
}

/// Generate the SDK source for every `(target, module)` pair, mapping each module
/// to its idiomatic sub-package (steered by `config`) with each target's idiomatic
/// casing. Each file's text is rough (unformatted) so callers run the real
/// formatter when they write it out. Fails if the bespoke gate
/// ([`extensions::validate_extensions`]) rejects the model. [`generate_target`] is
/// the per-target, casing-overridable variant the manifest path uses.
pub fn generate(
    model: &Model,
    targets: &[TargetKind],
    config: &CodegenConfig,
) -> Result<Vec<GeneratedFile>, String> {
    crate::codegen::extensions::validate_extensions(model)?;
    let langs: Vec<&[&str]> = targets.iter().map(|t| t.binding_langs()).collect();
    crate::codegen::extensions::validate_impl_coverage(model, &langs)?;
    crate::codegen::entries::validate_entries(model, targets)?;
    crate::codegen::declared_tests::validate_declared_tests(model)?;
    crate::codegen::ops::validate_error_codes(model)?;
    let (model, union_ids, exposed) = prepare(model, config);
    let mut files = Vec::new();
    for &target in targets {
        files.extend(emit_target(
            &model,
            target,
            &casing_for(target),
            config,
            &union_ids,
            &exposed,
        ));
    }
    reject_duplicate_paths(&files)?;
    reject_unfilled_slots(&files)?;
    Ok(files)
}

/// Generate the SDK source for a single target with an explicit casing (the
/// manifest's `[target.<lang>.casing]` overrides layered on the language default).
/// Paths carry the `<target-dir>/` prefix, like [`generate`], so a config-driven
/// caller strips it and rewrites each target under its own configured `out`.
/// Subject to the same bespoke gate as [`generate`].
pub fn generate_target(
    model: &Model,
    target: TargetKind,
    config: &CodegenConfig,
    casing: &CasingConfig,
) -> Result<Vec<GeneratedFile>, String> {
    crate::codegen::extensions::validate_extensions(model)?;
    crate::codegen::extensions::validate_impl_coverage(model, &[target.binding_langs()])?;
    crate::codegen::entries::validate_entries(model, &[target])?;
    crate::codegen::declared_tests::validate_declared_tests(model)?;
    crate::codegen::ops::validate_error_codes(model)?;
    let (model, union_ids, exposed) = prepare(model, config);
    let files = emit_target(&model, target, casing, config, &union_ids, &exposed);
    reject_duplicate_paths(&files)?;
    reject_unfilled_slots(&files)?;
    Ok(files)
}

